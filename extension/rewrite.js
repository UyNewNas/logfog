  function format(template, match) {
    return template.replace(/\$(\d)/g, (placeholder, index, offset) => {
      const value = match[Number(index)].trim();
      if (!value) return '';
      const before = template[offset - 1] || '';
      const after = template[offset + placeholder.length] || '';
      const left = /[\u3400-\u9fff]/.test(before) && /^[A-Za-z0-9]/.test(value) ? ' ' : '';
      const right = /[A-Za-z0-9]$/.test(value) && /^[\u3400-\u9fff]/.test(after) ? ' ' : '';
      return left + value + right;
    });
  }

